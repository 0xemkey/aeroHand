"""Generate right_hand_mobile.xml: the official Aero Hand model with a 6-DoF actuated wrist.

The wrist is a floating base made of 3 slide joints (x, y, z) and 3 hinges (yaw about z,
pitch about y, roll about x, i.e. R = Rz(yaw) Ry(pitch) Rx(roll)), each driven by a position
actuator. Hand bodies get gravity compensation so the wrist does not sag. The finger actuators
keep indices 0-6; the wrist actuators are appended as 7-12.

Re-run after updating aero-open-sim:  python make_mobile_hand.py
"""
from pathlib import Path

MJCF_DIR = Path(__file__).parent / "aero-open-sim" / "mujoco"
SRC, OUT = MJCF_DIR / "right_hand.xml", MJCF_DIR / "right_hand_mobile.xml"

WRIST_POS = "0.04 0.01 -0.015"  # rotation center = palm origin, in the mount frame
SLIDE_RANGE, YAW_RANGE, PITCH_RANGE, ROLL_RANGE = 0.3, 3.1416, 1.5708, 3.1416
# Gains are limited by the model's 10 ms explicit-Euler step.
SLIDE_KP, SLIDE_KV, HINGE_KP, HINGE_KV = 400, 20, 4, 0.15

WRIST_JOINTS = [
    ("wrist_x", "slide", "1 0 0", SLIDE_RANGE),
    ("wrist_y", "slide", "0 1 0", SLIDE_RANGE),
    ("wrist_z", "slide", "0 0 1", SLIDE_RANGE),
    ("wrist_yaw", "hinge", "0 0 1", YAW_RANGE),
    ("wrist_pitch", "hinge", "0 1 0", PITCH_RANGE),
    ("wrist_roll", "hinge", "1 0 0", ROLL_RANGE),
]


def main():
    xml = SRC.read_text()
    mount_tag = '<body name="tetheria_mount" pos="0 0 -0.03" quat="1 0 0 0" childclass="tetheria_rh">'
    assert mount_tag in xml, "right_hand.xml changed upstream; update mount_tag"

    joints = "".join(
        f'\n      <joint name="{n}" type="{t}" axis="{a}" pos="{WRIST_POS}" range="{-r} {r}" '
        f'damping="0" frictionloss="0" armature="{0.05 if t == "slide" else 0.002}"/>'
        for n, t, a, r in WRIST_JOINTS)
    xml = xml.replace(mount_tag, mount_tag + "\n      <!-- 6-DoF wrist (added by make_mobile_hand.py) -->" + joints)
    xml = xml.replace("<body name=", '<body gravcomp="1" name=')
    xml = xml.replace('model="Tetheria_Aero_Hand_Open_RightHand"', 'model="Tetheria_Aero_Hand_Open_RightHand_Mobile"')

    acts = "".join(
        f'\n    <position name="{n}_A" joint="{n}" ctrlrange="{-r} {r}" '
        f'kp="{SLIDE_KP if t == "slide" else HINGE_KP}" kv="{SLIDE_KV if t == "slide" else HINGE_KV}"/>'
        for n, t, a, r in WRIST_JOINTS)
    xml = xml.replace("  </actuator>", "    <!-- wrist (added by make_mobile_hand.py) -->" + acts + "\n  </actuator>", 1)

    OUT.write_text("<!-- Generated by make_mobile_hand.py from right_hand.xml - do not edit by hand. -->\n" + xml)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
