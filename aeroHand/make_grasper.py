"""Generate grasper.xml: a pistol-grip laparoscopic grasper built from MuJoCo primitives.

Dimensions were measured from a product photo (33 cm shaft, ~14 x 13 cm handle).
Local frame: +x toward the jaw tip, +z up (top of the handle), origin at the center of the
white housing. Edit the numbers below and re-run:  python make_grasper.py
"""
from pathlib import Path

import numpy as np

OUT = Path(__file__).parent / "aero-open-sim" / "mujoco" / "grasper.xml"

SHAFT_R, SHAFT_START, SHAFT_END = 0.0025, 0.028, 0.34
JAW_LEN, JAW_OPEN_DEG = 0.02, 25
LOOP_R = 0.0065                       # tube radius of the blue finger loop
# Finger loop (fixed handle) outline in local (x, z); fingers go through it, robot grasps around it.
LOOP_PTS = [(-0.012, -0.012), (-0.030, -0.095), (-0.052, -0.098), (-0.058, -0.070),
            (-0.045, -0.022)]
THUMB_RING_C, THUMB_RING_R, THUMB_RING_TUBE = (-0.082, 0.006), 0.02, 0.005
RING_SEGMENTS = 12

# Masses (kg); total ~0.13 kg like a real reusable grasper
M_SHAFT, M_JAWS, M_HOUSING, M_KNOB, M_BODY, M_LOOP, M_RING = 0.025, 0.003, 0.02, 0.01, 0.02, 0.035, 0.015


def f(*v):
    return " ".join(f"{x:.4f}" for x in v)


def capsule(name, a, b, r, mat, mass):
    (ax, az), (bx, bz) = a, b
    return (f'<geom name="{name}" class="instrument" type="capsule" size="{r:.4f}" '
            f'fromto="{f(ax, 0, az, bx, 0, bz)}" material="{mat}" mass="{mass:.4f}"/>')


def main():
    g = []
    # Shaft and rotation knob
    # (fromto / quat only, so the file works whatever the including model's compiler angle unit is)
    g.append(f'<geom name="lap_shaft" class="instrument" type="cylinder" size="{SHAFT_R}" '
             f'fromto="{f(SHAFT_START, 0, 0, SHAFT_END, 0, 0)}" material="lap_shaft_black" mass="{M_SHAFT}"/>')
    g.append(f'<geom name="lap_knob" class="instrument" type="cylinder" size="0.013" '
             f'fromto="0.022 0 0 0.040 0 0" material="lap_white" mass="{M_KNOB}"/>')
    # Jaws: open V at the tip (box rotated about local y)
    a = np.radians(JAW_OPEN_DEG)
    for side, s in [("upper", 1), ("lower", -1)]:
        c = (SHAFT_END + 0.5 * JAW_LEN * np.cos(a), s * 0.5 * JAW_LEN * np.sin(a))
        q = (np.cos(-s * a / 2), 0, np.sin(-s * a / 2), 0)
        g.append(f'<geom name="lap_jaw_{side}" class="instrument" type="box" size="{JAW_LEN / 2:.4f} 0.0015 0.0008" '
                 f'pos="{f(c[0], 0, c[1])}" quat="{f(*q)}" material="lap_steel" mass="{M_JAWS / 2}"/>')
    # White housing + connector post, blue body behind it
    g.append(f'<geom name="lap_housing" class="instrument" type="box" size="0.022 0.013 0.016" pos="0 0 0" '
             f'material="lap_white" mass="{M_HOUSING}"/>')
    g.append('<geom name="lap_post" class="instrument" type="cylinder" size="0.004 0.008" pos="-0.012 0 0.022" '
             'material="lap_gray" mass="0.002"/>')
    g.append(f'<geom name="lap_body" class="instrument" type="box" size="0.02 0.009 0.014" pos="-0.035 0 0.002" '
             f'material="lap_blue" mass="{M_BODY}"/>')
    # Finger loop (closed polygon of capsules)
    m = M_LOOP / len(LOOP_PTS)
    for i, (p, q) in enumerate(zip(LOOP_PTS, LOOP_PTS[1:] + LOOP_PTS[:1])):
        g.append(capsule(f"lap_loop{i}", p, q, LOOP_R, "lap_blue", m))
    # Thumb ring (gray) on a blue lever
    g.append(capsule("lap_lever", (-0.05, 0.0), (THUMB_RING_C[0] + THUMB_RING_R, THUMB_RING_C[1]), 0.006, "lap_blue", 0.004))
    th = np.linspace(0, 2 * np.pi, RING_SEGMENTS + 1)
    pts = [(THUMB_RING_C[0] + THUMB_RING_R * np.cos(t), THUMB_RING_C[1] + THUMB_RING_R * np.sin(t)) for t in th]
    for i in range(RING_SEGMENTS):
        g.append(capsule(f"lap_ring{i}", pts[i], pts[i + 1], THUMB_RING_TUBE, "lap_gray", M_RING / RING_SEGMENTS))

    grasp_c = np.mean(LOOP_PTS, axis=0)
    body = "\n            ".join(g)
    xml = f"""<!-- Generated by make_grasper.py - edit that script instead of this file. -->
<mujoco model="laparoscopic_grasper">
    <asset>
        <material name="lap_blue" rgba="0.12 0.25 0.7 1" specular="0.3"/>
        <material name="lap_white" rgba="0.92 0.92 0.9 1"/>
        <material name="lap_gray" rgba="0.6 0.6 0.62 1"/>
        <material name="lap_steel" rgba="0.75 0.77 0.8 1" specular="0.9" shininess="0.8"/>
        <material name="lap_shaft_black" rgba="0.12 0.12 0.13 1" specular="0.6"/>
    </asset>

    <default>
        <!-- contype/conaffinity 1|2: touches the hand (1) and the floor (2) -->
        <default class="instrument">
            <geom contype="1" conaffinity="3" friction="1.0 0.02 0.001" condim="4"
                  solref="0.01 1" solimp="0.95 0.99 0.001"/>
        </default>
    </default>

    <worldbody>
        <!-- Pose is set by the scene's keyframe; this is only the default spawn. -->
        <body name="laparoscope" pos="0 0 0.3">
            <freejoint name="laparoscope_free"/>
            <site name="laparoscope_grip_center" pos="{f(grasp_c[0], 0, grasp_c[1])}" size="0.003" rgba="1 0 0 1" group="4"/>
            <site name="laparoscope_tip" pos="{f(SHAFT_END + JAW_LEN, 0, 0)}" size="0.002" rgba="0 1 0 1" group="4"/>
            {body}
        </body>
    </worldbody>
</mujoco>
"""
    OUT.write_text(xml)
    print(f"wrote {OUT}  (grip center local x,z = {np.round(grasp_c, 4)})")


if __name__ == "__main__":
    main()
